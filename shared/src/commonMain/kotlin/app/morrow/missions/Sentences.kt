package app.morrow.missions

import app.morrow.domain.Difficulty

/** Short, upbeat sentences for Type and Unscramble. Gentle has 4 to 6 words, Normal 6 to 9 and Tough 9 to 12. */
fun sentences(difficulty: Difficulty): List<String> = when (difficulty) {
    Difficulty.GENTLE -> Gentle
    Difficulty.NORMAL -> Normal
    Difficulty.TOUGH -> Tough
}

/** The same sentences without their full stop, for Unscramble. No sentence repeats a word. */
fun scrambleSentences(difficulty: Difficulty): List<String> = sentences(difficulty).map { it.trimEnd('.') }

internal fun wordsOf(sentence: String): List<String> = sentence.split(' ').filter { it.isNotEmpty() }

